package com.attendance;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.time.LocalDate;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import com.zaxxer.hikari.HikariDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.web.server.ResponseStatusException;

class AcademicTest {
    private static final UUID COURSE = UUID.fromString("41000000-0000-0000-0000-000000000001");
    private static final UUID OFFERING = UUID.fromString("42000000-0000-0000-0000-000000000001");
    private static final UUID SECOND_OFFERING = UUID.fromString("42000000-0000-0000-0000-000000000002");
    private static final UUID TEACHER = UUID.fromString("43000000-0000-0000-0000-000000000001");
    private static final UUID CO_TEACHER = UUID.fromString("43000000-0000-0000-0000-000000000002");
    private static final UUID STUDENT = UUID.fromString("44000000-0000-0000-0000-000000000001");

    private HikariDataSource dataSource;
    private JdbcTemplate jdbc;
    private Academic academic;

    @BeforeEach
    void setUp() {
        dataSource = new HikariDataSource();
        dataSource.setJdbcUrl("jdbc:h2:mem:academic;MODE=PostgreSQL;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
        dataSource.setUsername("sa");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("drop all objects");
        jdbc.execute("create table courses(id uuid primary key,course_code varchar(32) unique,name varchar(160),teacher varchar(100),archived boolean default false)");
        jdbc.execute("create table teacher_profiles(id uuid primary key,username varchar(100) unique,display_name varchar(100),active boolean not null default true,password_hash varchar(100))");
        jdbc.execute("create table students(id uuid primary key,name varchar(100),roll varchar(30),archived boolean default false)");
        jdbc.execute("create table student_accounts(id uuid primary key,student_id uuid unique,username varchar(100),email varchar(254),password_hash varchar(100),account_status varchar(20),active boolean,must_change_password boolean,registration_source varchar(30),created_by varchar(100),created_at timestamp default current_timestamp,updated_at timestamp default current_timestamp)");
        jdbc.execute("create table course_offerings(id uuid primary key,course_id uuid,academic_term varchar(40),academic_year int,batch varchar(40),section varchar(40),archived boolean default false,legacy boolean default false,unique(course_id,academic_term,academic_year,batch,section))");
        jdbc.execute("create table teacher_assignments(id uuid primary key,offering_id uuid,teacher_id uuid,assignment_role varchar(20),effective_from date,effective_to date,legacy boolean default false,created_by varchar(100))");
        jdbc.execute("create table offering_enrollments(id uuid primary key,offering_id uuid,student_id uuid,status varchar(20),active_from date,active_to date,source varchar(20),created_by varchar(100))");
        jdbc.execute("create unique index offering_enrollments_one_active on offering_enrollments(offering_id,student_id,status)");
        jdbc.execute("create table offering_enrollment_audit(id bigint generated by default as identity primary key,offering_id uuid,student_id uuid,actor varchar(100),action varchar(20))");
        jdbc.update("insert into courses values(?,?,?,'teacher',false)", COURSE, "CSE101", "Introduction to Computing");
        jdbc.update("insert into teacher_profiles values(?,?,?,true,null)", TEACHER, "teacher", "Teacher One");
        jdbc.update("insert into teacher_profiles values(?,?,?,true,null)", CO_TEACHER, "teacher-two", "Teacher Two");
        jdbc.update("insert into student_accounts(id,student_id,username,email,password_hash,account_status,active,must_change_password,registration_source,created_by) "
                        + "values(?,?,?,?,'$2a$10$abcdefghijklmnopqrstuuABCDEFGHIJKLMNOPQRSTUVWXYZ123456','APPROVED',true,false,'ADMIN','admin')",
                UUID.randomUUID(), STUDENT, "student-one", "student@example.edu");
        jdbc.update("insert into students values(?,?,?,false)", STUDENT, "Student One", "S001");
        jdbc.update("insert into course_offerings values(?,?,? ,?,?,?,false,false)",
                OFFERING, COURSE, "Spring", 2026, "2024", "A");
        jdbc.update("insert into teacher_assignments values(?,?,?,?,?,?,false,'admin')",
                UUID.randomUUID(), OFFERING, TEACHER, "PRIMARY", LocalDate.of(2026, 1, 1), null);
        academic = new Academic(jdbc, new BCryptPasswordEncoder());
    }

    @AfterEach
    void tearDown() {
        dataSource.close();
    }

    @Test
    void reusableCourseCanHaveDistinctOfferingsAndDuplicateIdentityIsRejected() {
        academic.createOffering(new Academic.NewOffering(COURSE, "Fall", 2026, "2024", "A"), admin());
        assertThrows(ResponseStatusException.class,
                () -> academic.createOffering(new Academic.NewOffering(COURSE, "Spring", 2026, "2024", "A"), admin()));
        assertEquals(2, jdbc.queryForObject("select count(*) from course_offerings where course_id=?", Integer.class, COURSE));
        assertEquals(1, jdbc.queryForObject("select count(*) from courses where id=?", Integer.class, COURSE));
    }

    @Test
    void teacherAccountsArePersistedWithOneWayPasswordHashes() {
        String password = "a-strong-teacher-password";
        BCryptPasswordEncoder encoder = new BCryptPasswordEncoder();
        academic.createTeacherProfile(
                new Academic.NewTeacherProfile("teacher-three", "Teacher Three", password), admin());

        String hash = jdbc.queryForObject("select password_hash from teacher_profiles where username=?",
                String.class, "teacher-three");
        assertTrue(!hash.equals(password));
        assertTrue(encoder.matches(password, hash));
        var user = new Security().users(jdbc, encoder).loadUserByUsername("teacher-three");
        assertTrue(user.isEnabled());
        assertTrue(encoder.matches(password, user.getPassword()));
    }

    @Test
    void assignmentsValidateDatesAndPreservePrimaryAndCoTeacherRoles() {
        assertThrows(ResponseStatusException.class,
                () -> academic.assignTeacher(new Academic.NewAssignment(
                        OFFERING, CO_TEACHER, "PRIMARY", LocalDate.of(2026, 2, 1), null), admin()));
        assertThrows(ResponseStatusException.class,
                () -> academic.assignTeacher(new Academic.NewAssignment(
                        OFFERING, CO_TEACHER, "CO_TEACHER", LocalDate.of(2026, 3, 1),
                        LocalDate.of(2026, 2, 28)), admin()));

        academic.assignTeacher(new Academic.NewAssignment(
                OFFERING, CO_TEACHER, "CO_TEACHER", LocalDate.of(2026, 1, 1), null), admin());
        assertEquals(2, jdbc.queryForObject("select count(*) from teacher_assignments where offering_id=?",
                Integer.class, OFFERING));
        jdbc.update("insert into course_offerings values(?,?,? ,?,?,?,false,false)",
                SECOND_OFFERING, COURSE, "Fall", 2026, "2024", "B");
        academic.assignTeacher(new Academic.NewAssignment(
                SECOND_OFFERING, CO_TEACHER, "PRIMARY", LocalDate.of(2026, 1, 1), null), admin());
        assertEquals(1, jdbc.queryForObject("select count(*) from teacher_assignments where offering_id=? and assignment_role='PRIMARY'",
                Integer.class, SECOND_OFFERING));
    }

    @Test
    void enrollmentIsOfferingScopedAndTeachersOnlySeeAssignedRosters() {
        academic.enroll(OFFERING, STUDENT, admin());
        assertThrows(ResponseStatusException.class, () -> academic.enroll(OFFERING, STUDENT, admin()));
        var roster = castRows(academic.offeringRoster(OFFERING, teacher()));
        assertEquals(1, roster.size());
        assertEquals("S001", roster.get(0).get("roll"));

        jdbc.update("insert into course_offerings values(?,?,? ,?,?,?,false,false)",
                SECOND_OFFERING, COURSE, "Fall", 2026, "2024", "B");
        assertThrows(ResponseStatusException.class, () -> academic.offeringRoster(SECOND_OFFERING, teacher()));
        assertThrows(ResponseStatusException.class, () -> academic.enroll(OFFERING, STUDENT, teacher()));
    }

    @Test
    void courseAndAssignmentAdministrationIsAdminOnly() {
        assertThrows(ResponseStatusException.class,
                () -> academic.createCourse(new Academic.NewCourse("CSE102", "Algorithms"), teacher()));
        assertThrows(ResponseStatusException.class,
                () -> academic.createTeacherProfile(
                        new Academic.NewTeacherProfile("teacher-three", "Teacher Three", "a-strong-password"), teacher()));
        assertThrows(ResponseStatusException.class, () -> academic.teacherProfiles(teacher()));
        Map<String, Object> created = cast(academic.createCourse(
                new Academic.NewCourse("cse102", "Algorithms"), admin()));
        assertEquals("CSE102", jdbc.queryForObject(
                "select course_code from courses where id=?", String.class, created.get("id")));
        assertTrue(jdbc.queryForObject("select count(*) from courses where archived=false", Integer.class) >= 1);
    }

    private static UsernamePasswordAuthenticationToken teacher() {
        return new UsernamePasswordAuthenticationToken("teacher", "",
                List.of(new SimpleGrantedAuthority("ROLE_TEACHER")));
    }

    private static UsernamePasswordAuthenticationToken admin() {
        return new UsernamePasswordAuthenticationToken("admin", "",
                List.of(new SimpleGrantedAuthority("ROLE_ADMIN")));
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> cast(Object value) {
        return (Map<String, Object>) value;
    }

    @SuppressWarnings("unchecked")
    private static List<Map<String, Object>> castRows(Object value) {
        return (List<Map<String, Object>>) value;
    }
}
